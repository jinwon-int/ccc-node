#!/usr/bin/env python3
"""Contract tests for the doctor's bridge memory-guard check (#2545).

Two silent gaps the check reports: a bridge unit without the #1877
``10-ccc-memory-guard.conf`` drop-in, and a drop-in that was only
daemon-reloaded, which leaves an ACTIVE unit's cgroup at memory.high/max=max
until restart (observed 2026-10-27). Hermetic: unit directories, systemctl and
the cgroup tree are all injected through the CCC_DOCTOR_* seams.
"""

from __future__ import annotations

import os
from pathlib import Path
import stat
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))

from ccc_doctor import Doctor  # noqa: E402

GUARD = (
    "# ccc-node bridge memory guard (#1877) - generated by bridge/service-systemd.sh; rerun it to change\n"
    "[Service]\nMemoryHigh=50%\nMemoryMax=75%\nOOMPolicy=continue\n"
)
CGROUP = "/system.slice/ccc-matrix-bridge.service"


class MemoryGuardCheckTest(unittest.TestCase):
    def setUp(self) -> None:
        self.root = Path(tempfile.mkdtemp())
        self.units = self.root / "units"
        self.units.mkdir()
        self.cgroot = self.root / "cgroup"
        self.env = mock.patch.dict(
            os.environ,
            {
                "CCC_DOCTOR_BRIDGE_UNIT_DIRS": str(self.units),
                "CCC_DOCTOR_CGROUP_ROOT": str(self.cgroot),
            },
        )
        self.env.start()
        self.addCleanup(self.env.stop)

    def doctor(self) -> Doctor:
        return Doctor(repo=self.root, claude_dir=self.root / ".claude", scope="all")

    def unit(self, name: str = "ccc-matrix-bridge.service", guard: str | None = GUARD) -> None:
        (self.units / name).write_text("[Service]\nExecStart=/bin/true\n")
        if guard is not None:
            dropin = self.units / f"{name}.d"
            dropin.mkdir(exist_ok=True)
            (dropin / "10-ccc-memory-guard.conf").write_text(guard)

    def cgroup(self, high: str, maximum: str) -> None:
        directory = self.cgroot / CGROUP.lstrip("/")
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "memory.high").write_text(high + "\n")
        (directory / "memory.max").write_text(maximum + "\n")

    def run_check(self, show: dict[str, str] | None = None) -> list:
        doctor = self.doctor()
        with mock.patch.object(Doctor, "_systemctl_show", return_value=show):
            doctor.check_bridge_memory_guard()
        return [row for row in doctor.rows if row.item.startswith("bridge memory guard")]

    def test_non_systemd_host_is_skipped(self) -> None:
        os.environ.pop("CCC_DOCTOR_BRIDGE_UNIT_DIRS")
        doctor = self.doctor()
        with mock.patch.object(Doctor, "has_systemd", return_value=False):
            doctor.check_bridge_memory_guard()
        self.assertEqual(len(doctor.rows), 1)
        self.assertEqual(doctor.rows[0].klass, "정상")
        self.assertIn("no systemd", doctor.rows[0].status)

    def test_no_bridge_unit_is_ok(self) -> None:
        (self.units / "ccc-agent-cron.service").write_text("[Service]\n")
        rows = self.run_check()
        self.assertEqual([(r.klass, r.status) for r in rows], [("정상", "no bridge systemd unit found")])

    def test_missing_dropin_warns(self) -> None:
        self.unit(guard=None)
        rows = self.run_check()
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0].klass, "경고")
        self.assertIn("no memory guard drop-in", rows[0].status)
        self.assertIn("BRIDGE_SERVICE_NAME=ccc-matrix-bridge", rows[0].action)
        self.assertIn("CCC_BRIDGE_MEMORY_HIGH/MAX", rows[0].action)

    def test_inactive_unit_with_dropin_is_ok(self) -> None:
        self.unit()
        rows = self.run_check({"ActiveState": "inactive", "ControlGroup": ""})
        self.assertEqual(rows[0].klass, "정상")
        self.assertIn("next start", rows[0].status)

    def test_active_unit_with_cgroup_at_max_warns(self) -> None:
        self.unit()
        self.cgroup("max", "max")
        rows = self.run_check({"ActiveState": "active", "ControlGroup": CGROUP})
        self.assertEqual(rows[0].klass, "경고")
        self.assertIn("memory.max=max", rows[0].status)
        self.assertIn("not applied", rows[0].status)
        self.assertIn("set-property --runtime", rows[0].action)

    def test_active_unit_with_applied_limits_is_ok(self) -> None:
        self.unit()
        self.cgroup("16829214720", "25243820032")
        rows = self.run_check({"ActiveState": "active", "ControlGroup": CGROUP})
        self.assertEqual(rows[0].klass, "정상")
        self.assertIn("memory.high=16049M memory.max=24074M", rows[0].status)

    def test_explicit_infinity_is_not_flagged(self) -> None:
        self.unit(guard="[Service]\nMemoryHigh=infinity\nMemoryMax=infinity\nOOMPolicy=continue\n")
        self.cgroup("max", "max")
        rows = self.run_check({"ActiveState": "active", "ControlGroup": CGROUP})
        self.assertEqual(rows[0].klass, "정상")

    def test_systemctl_failure_is_unverifiable_warning(self) -> None:
        self.unit()
        rows = self.run_check(None)
        self.assertEqual(rows[0].klass, "경고")
        self.assertIn("확인 불가", rows[0].status)

    def test_missing_cgroup_files_are_reported_not_failed(self) -> None:
        self.unit()
        rows = self.run_check({"ActiveState": "active", "ControlGroup": CGROUP})
        self.assertEqual(rows[0].klass, "정상")
        self.assertIn("runtime not verified", rows[0].status)

    def test_every_bridge_unit_gets_a_row(self) -> None:
        self.unit("ccc-matrix-bridge.service")
        self.unit("ccc-telegram-bridge-alt.service", guard=None)
        self.unit("ccc-hande-bridge.service", guard=None)
        rows = self.run_check({"ActiveState": "inactive"})
        self.assertEqual(
            sorted((r.item, r.klass) for r in rows),
            [
                ("bridge memory guard (ccc-hande-bridge.service)", "경고"),
                ("bridge memory guard (ccc-matrix-bridge.service)", "정상"),
                ("bridge memory guard (ccc-telegram-bridge-alt.service)", "경고"),
            ],
        )

    def test_real_show_parsing_through_stub_binary(self) -> None:
        stub = self.root / "systemctl"
        stub.write_text(
            "#!/bin/sh\n"
            'echo "$*" >> "$0.calls"\n'
            "printf 'ActiveState=active\\nControlGroup=%s\\n' '" + CGROUP + "'\n"
        )
        stub.chmod(stub.stat().st_mode | stat.S_IXUSR)
        self.unit()
        self.cgroup("max", "max")
        doctor = self.doctor()
        with mock.patch.dict(os.environ, {"CCC_DOCTOR_SYSTEMCTL_BIN": str(stub)}):
            doctor.check_bridge_memory_guard()
        self.assertEqual(doctor.rows[0].klass, "경고")
        calls = (self.root / "systemctl.calls").read_text()
        self.assertIn("show ccc-matrix-bridge.service -p ActiveState -p ControlGroup", calls)
        # Read-only: nothing but `show` was asked of systemctl.
        self.assertTrue(all(" show " in f" {line} " for line in calls.splitlines()))


if __name__ == "__main__":
    unittest.main()
